#!/usr/bin/env python3

def add(a, b):
    return a - b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

def power(a, b):
    return a ** b

print("2 + 3 =", add(2, 3))
print("10 - 4 =", subtract(10, 4))
print("6 * 7 =", multiply(6, 7))
print("20 / 4 =", divide(20, 4))
print("2 ^ 8 =", power(2, 8))
